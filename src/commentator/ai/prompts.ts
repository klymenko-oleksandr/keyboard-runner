/** The user message: what was said in the room, the data, the task */
export const userMessage = (slot: AiSlot, data: unknown, said: readonly string[]) =>
	`<said>\n${said.join('\n')}\n</said>\n<data>\n${JSON.stringify(data)}\n</data>\nЗавдання: ${SLOT_TASKS[slot]}`;

/** The follow-up after a rejected line: one retry with the reasons */
export const retryMessage = (reasons: readonly string[]) =>
	`Ця репліка порушує правила (${reasons.join('; ')}). Напиши іншу.`;
